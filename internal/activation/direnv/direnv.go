// Package direnv owns the direnv activation backend: generating and parsing
// .envrc files, controlling direnv (allow/deny/reload), silencing direnv output
// and migrating legacy projects. It is the first activation backend; the
// Activator interface that makes it interchangeable lands in v3.1.
